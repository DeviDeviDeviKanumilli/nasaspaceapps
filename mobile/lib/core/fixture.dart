/// Ground plane y = 0 (2 x 2 m) with Gaussian noise [noiseM], plus a half-ellipsoid boulder
/// (semi-axes 0.45, 0.35, 0.30 m) centred at the origin. Point spacing [spacing] metres.
PointCloud syntheticBoulder({double spacing = 0.01, double noiseM = 0.002, int seed = 7}) {
  final rnd = math.Random(seed);
  double gauss() {
    final u = math.max(1e-12, rnd.nextDouble()), v = rnd.nextDouble();
    return math.sqrt(-2 * math.log(u)) * math.cos(2 * math.pi * v);
  }

  const a = 0.45, b = 0.30, c = 0.35;
  final xyz = <double>[], rgb = <int>[], conf = <int>[];
  for (double x = -1; x <= 1; x += spacing) {
    for (double z = -1; z <= 1; z += spacing) {
      final q = (x * x) / (a * a) + (z * z) / (c * c);
      double y = 0;
      bool rock = false;
      if (q < 1) {
        y = b * math.sqrt(1 - q);
        rock = true;
      }
      xyz.addAll([x, y + gauss() * noiseM, z]);
      final g = rock ? 95 + rnd.nextInt(30) : 120 + rnd.nextInt(25);
      rgb.addAll(rock ? [g, g, g + 8] : [g, (g * 0.85).round(), (g * 0.6).round()]);
      conf.add(2);
    }
  }
  return PointCloud(Float32List.fromList(xyz), rgb: Uint8List.fromList(rgb), confidence: Uint8List.fromList(conf));
}

Future<ScanRecord> writeSyntheticScan(ScanLibrary lib) async {
  final id = newId();
  final dir = lib.newScanDir(id)..createSync(recursive: true);
  final pc = syntheticBoulder();
  final ply = writePly(pc, comments: ['SYNTHETIC TEST FIXTURE generated by Field Scan; not a real scan', 'frame arkit_session_world-like, metres, +Y up']);
  File('${dir.path}/point_cloud_fused.ply').writeAsBytesSync(ply);
  final now = utcNow();
  final env = {
    'schema_version': schemaVersion,
    'scan_id': id,
    'session_id': id,
    'status': 'complete',
    'is_real_sensor': false,
    'origin': 'synthetic_fixture',
    'platform': 'ios',
    'device': {'manufacturer': 'none', 'model': 'synthetic generator', 'model_identifier': 'synthetic', 'os_version': null},
    'app': {'name': appName, 'version': appVersion, 'pipeline_version': pipelineVersion},
    'captured_at_utc': {'start': now, 'end': now},
    'capture': {'depth_type': 'synthetic', 'keyframes': 0, 'photos': 0, 'mesh_present': false, 'tracking_poses_present': false},
    'coordinate_frame': {'name': 'arkit_session_world', 'units': 'm', 'handedness': 'right', 'up': '+Y'},
    'location': {'sharing': 'hidden', 'collected': false},
    'observation': {
      'title': 'SYNTHETIC boulder (test fixture)',
      'feature_type': 'boulder',
      'notes': 'Half-ellipsoid 0.90 x 0.70 m footprint, 0.30 m tall, on flat ground with 2 mm Gaussian noise, 1 cm spacing. '
          'Expected: ground ROI roughness ~2 mm and tilt ~0°; boulder height 0.30 m.',
      'claims': [],
    },
    'quality': {'fused_points': pc.length, 'keyframes': 0},
    'measurements': [],
    'files': [
      {
        'path': 'point_cloud_fused.ply',
        'role': 'derived_point_cloud',
        'kind': 'derived',
        'mime': 'application/x-ply',
        'bytes': ply.length,
        'sha256': sha256.convert(ply).toString(),
        'lineage': 'generated by syntheticBoulder() in lib/core/fixture.dart',
      }
    ],
    'processing': {
      'pipeline_version': pipelineVersion,
      'operations': [
        {'op': 'synthetic_generate', 'params': {'spacing_m': 0.01, 'noise_m': 0.002, 'seed': 7}},
        {'op': 'voxel_fuse', 'params': {'voxel_m': 0.01}, 'note': 'not applied; listed so the viewer uses 1 cm for its notes'},
      ],
    },
    'publication': {'status': 'local_private', 'license': null, 'consent_obtained': false},
    'limitations': ['SYNTHETIC: generated geometry for software testing. Not a measurement of anything real.'],
    'revisions': [
      {'utc': now, 'change': 'synthetic fixture generated'}
    ],
  };
  File('${dir.path}/scan.json').writeAsStringSync(const JsonEncoder.withIndent(' ').convert(env));
  return ScanRecord(dir, env);
}
